import { mailThread, message, mailDraft, mailDraftRevision, aiWorkflowRun } from '../src/db/schema/mail.js';
import { configureDraftArtifactStorage } from '../src/trpc/routes/drafts.js';
import { withSeededTestDb, probeTestDb } from './helpers/test-db';
import { toDraftWire } from '../src/trpc/routes/draft-wire.js';
import { persistAiCandidateDraft } from '../src/ai/drafts.js';
import { randomUUID, createHash } from 'node:crypto';
import { callerFor } from './helpers/trpc-caller';
import { TRANSPORT_ID } from '../src/db/seed.js';
import { expect, it } from 'vitest';
import { eq } from 'drizzle-orm';
if (!(await probeTestDb())) throw new Error('U7 requires disposable DB');
it('stages and verifies generated bytes before draft/revision/typed-result links', async () => {
  await withSeededTestDb(async (db) => {
    const deadline = new Date(Date.now() + 600000);
    const threadId = randomUUID(),
      parent = randomUUID(),
      runId = randomUUID();
    await db.insert(mailThread).values({
      id: threadId,
      transportId: TRANSPORT_ID,
      threadRootId: 'synthetic-' + threadId,
      latestMessageAt: new Date(),
    });
    await db.insert(message).values({
      id: parent,
      threadId,
      transportId: TRANSPORT_ID,
      direction: 'inbound',
      fromAddress: 'synthetic@example.com',
      toAddresses: [],
      receivedAt: new Date(),
    });
    await db.insert(aiWorkflowRun).values({
      id: runId,
      threadId,
      transportId: TRANSPORT_ID,
      triggerMessageId: parent,
      state: 'running',
      claimOwner: 'synthetic-owner',
      claimToken: 'synthetic-token',
      deadlineAt: deadline,
      runKind: 'candidate_draft',
      idempotencyKey: runId,
      modelId: 'synthetic',
      promptVersion: 'synthetic',
    });
    const body = Buffer.from('%PDF-synthetic'),
      hash = createHash('sha256').update(body).digest('hex');
    const objects = new Map<string, Buffer>();
    const input = {
      db,
      transportId: TRANSPORT_ID,
      threadId,
      replyToMessageId: parent,
      createdByUserId: 'user-navaai',
      generationId: randomUUID(),
      model: 'synthetic',
      promptVersion: 'synthetic',
      contextMessageIds: [parent],
      toAddresses: [],
      subject: 'Synthetic',
      textBody: 'Synthetic',
      htmlBody: '<p>Synthetic</p>',
      persistDraft: true,
      workflowRunId: runId,
      revalidateSources: async () => true,
      runFence: {
        claimOwner: 'synthetic-owner',
        claimToken: 'synthetic-token',
        deadlineAt: deadline,
      },
      reservationistResult: {
        version: 1,
        readiness: 'staff_review',
        tasks: [],
        quoteRevisionIds: [],
        artifactRefs: ['generated:quote'],
        actionDigest: 'a'.repeat(64),
      },
      generatedArtifacts: [
        {
          artifactRef: 'generated:quote',
          filename: 'quote.pdf',
          mimeType: 'application/pdf',
          body,
          sha256: hash,
        },
      ],
      artifactStorage: {
        stage: async (key: string, value: Buffer) => {
          objects.set(key, value);
        },
        read: async (key: string) => objects.get(key) ?? null,
      },
    };
    const orphanKeys: string[] = [];
    await expect(
      persistAiCandidateDraft({
        ...input,
        generationId: randomUUID(),
        threadStateVersion: 'stale',
        onGeneratedOrphans: (keys: string[]) => orphanKeys.push(...keys),
      } as any),
    ).rejects.toThrow(/stale/);
    expect(orphanKeys).toHaveLength(1);
    await expect(
      persistAiCandidateDraft({
        ...input,
        generationId: randomUUID(),
        runFence: { ...input.runFence, claimToken: 'stolen' },
      } as any),
    ).rejects.toThrow(/claim/);
    await expect(
      persistAiCandidateDraft({
        ...input,
        generationId: randomUUID(),
        revalidateSources: async () => false,
      } as any),
    ).rejects.toThrow(/source/);
    let sourceChecks = 0;
    await expect(
      persistAiCandidateDraft({
        ...input,
        generationId: randomUUID(),
        revalidateSources: async () => ++sourceChecks === 1,
      } as any),
    ).rejects.toThrow(/source/);
    expect(sourceChecks).toBe(2);
    const persisted = await persistAiCandidateDraft(input as any);
    // This test requests a persisted draft; generation-only results are a failure.
    expect(persisted).toHaveProperty('attachments');
    const result = persisted as typeof mailDraft.$inferSelect;
    expect(result.attachments).toHaveLength(1);
    await expect(
      persistAiCandidateDraft({
        ...input,
        reservationistResult: { ...input.reservationistResult, actionDigest: 'b'.repeat(64) },
      } as any),
    ).rejects.toThrow(/result/);
    const revisions = await db
      .select()
      .from(mailDraftRevision)
      .where(eq(mailDraftRevision.draftId, result.id));
    expect(revisions[0].attachments).toEqual(result.attachments);
    const caller = await callerFor('user-navaai', { db, requestedTransportId: TRANSPORT_ID });
    configureDraftArtifactStorage(input.artifactStorage);
    const promoted = await caller.drafts.ensureEditableForReply({
      threadId,
      replyToMessageId: parent,
    });
    expect(promoted.attachments[0].sourceHash).toBe(hash);
    const loaded = await caller.drafts.getArtifact({
      draftId: result.id,
      artifactRef: 'generated:quote',
    });
    expect(loaded.base64).toBe(body.toString('base64'));
    objects.clear();
    await expect(
      caller.drafts.getArtifact({ draftId: result.id, artifactRef: 'generated:quote' }),
    ).rejects.toMatchObject({ code: 'CONFLICT' });
    configureDraftArtifactStorage(null);
    const wire = toDraftWire(result);
    expect(wire.attachments[0].sourceHash).toBe(hash);
    expect(JSON.stringify(wire)).not.toContain('s3Key');
    const [run] = await db.select().from(aiWorkflowRun).where(eq(aiWorkflowRun.id, runId));
    expect(run.metrics?.resultDigest).toMatch(/^[a-f0-9]{64}$/);
    await expect(
      persistAiCandidateDraft({
        ...input,
        generationId: randomUUID(),
        artifactStorage: { ...input.artifactStorage, read: async () => Buffer.from('changed') },
      } as any),
    ).rejects.toThrow(/artifact/);
  });
});
